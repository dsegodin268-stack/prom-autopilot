# -*- coding: utf-8 -*-
"""«Сумісність з моделлю» і роздільник крос-номерів.

28.07. Бойовий рядок 2152 («Пильник амортизатора (переднього) BMW 3 (F30)/4
(F33)/M4 (F83)», артикул 31306791712) приїхав із двома дефектами в
характеристиках:

1. «Сумісність з моделлю = 3». Це не модель, це серія. _model_of() повертала
   РІВНО одну модель і чіпляла код кузова, лише якщо той схожий на «G20» —
   кузов у дужках «(F30)» під правило не підпадав, а скісна риска між моделями
   не різалась узагалі. Покупець із F30 картку не знаходить, а власник будь-якої
   «трійки» бачить деталь, яка йому не підходить.

2. «Кросс-номери = …;1127404SX,159000115;…». BM Parts подекуди кладе в article
   аналога кілька номерів через кому. Prom розбирає кроси СУВОРО по «;», тому
   така пара не працює цілком: обидва номери склеєні в один неіснуючий.
"""
from adding.card_builder import _models, _models_of, _oem_repl, canon_chars

PROD = {
    "name": "Пильник амортизатора (переднього) BMW 3 (F30)/4 (F33)/M4 (F83)",
    "brand": "BMW",
    "article": "31306791712",
    "images": ["x.jpg"],
    "oe": [{"number": "31 30 6 791 712", "is_oem": True}],
    "analogs": {"1": {"article": "1127404SX,159000115"},
                "2": {"article": "005.0409", "brand": "ZENTPARTS"}},
}


def _ch(product, name):
    for n, _u, v in canon_chars(product, {}, None):
        if n == name:
            return v
    return ""


# ---------- модель + кузов ----------
def test_кузов_у_дужках_доїжджає():
    assert _models_of("BMW 3 (F30)/4 (F33)/M4 (F83)", "BMW") == \
        ["3 (F30)", "4 (F33)", "M4 (F83)"]


def test_голий_кузов_із_довідника_як_і_був():
    """Стара поведінка для рядків BM Parts не змінюється: код двигуна (B48) не
    беремо — за ним у «Сумісності з моделлю» ніхто не фільтрує."""
    assert _models_of("BMW 3 G20 B48 2018+", "BMW") == ["3 G20"]


def test_серія_тягнеться_на_другий_кузов():
    assert _models_of("BMW 3 (F30)/(F31)", "BMW") == ["3 (F30)", "3 (F31)"]


def test_кілька_серій_через_риску():
    assert _models_of("BMW X3 F25/X4 F26", "BMW") == ["X3 F25", "X4 F26"]


def test_порожній_рядок_нічого_не_дає():
    assert _models_of("", "BMW") == []
    assert _models_of("BMW", "BMW") == []


def test_роки_не_стають_моделлю():
    assert _models_of("BMW 5 G30 2016-2020", "BMW") == ["5 G30"]


def test_models_збирає_всі_рядки():
    assert _models(["BMW 3 (F30)/4 (F33)", "BMW 5 G30"], "BMW") == \
        ["3 (F30)", "4 (F33)", "5 G30"]


def test_характеристика_моделі_в_картці():
    assert _ch(PROD, "Сумісність з моделлю") == "3 (F30)|4 (F33)|M4 (F83)"


# ---------- крос-номери ----------
def test_список_у_одному_полі_розбивається():
    _oem, repl = _oem_repl(PROD)
    assert "1127404SX" in repl and "159000115" in repl
    assert not any("," in r for r in repl), repl


def test_кроси_тільки_через_крапку_з_комою():
    v = _ch(PROD, "Кросс-номери")
    assert "," not in v, v
    assert "1127404SX" in v.split(";") and "159000115" in v.split(";")


def test_свій_артикул_не_потрапляє_в_кроси():
    assert "31306791712" not in _ch(PROD, "Кросс-номери").split(";")
