# -*- coding: utf-8 -*-
# Рівень і маршрут по ГОТОВІЙ картці, а не по сирому кандидату.
#
# Навіщо цей файл окремо від test_completeness.py: там перевіряється рішення
# про СИРОВИНУ (що показати власникові в «Огляд_Додавання»), тут — рішення про
# ГОТОВУ картку (куди її записати). Це два різні питання, і плутанина між ними
# й була дефектом прогону №18: позиція з 10 характеристиками, 3 фото, групою і
# підрозділом лягла в чернетку з написом «нема характеристик, сумісності», бо
# рівень рахувався з прайсу постачальника, де цього справді не було.
from adding.completeness import (describe_card, level_card, missing_card,
                                 route_card)

IMGS = ["https://cdn.bm.parts/a.jpg", "https://cdn.bm.parts/b.jpg"]

FULL = [("Стан", "", "Новий"),
        ("Сумісність з маркою", "", "BMW"),
        ("Сумісність з моделлю", "", "3 (F30)|4 (F33)"),
        ("Рік випуску автомобіля", "", "2011-2019"),
        ("Тип запчастини", "", "Оригінал"),
        ("Код запчастини", "", "31306791712"),
        ("Тип техніки", "", "Легковий автомобіль"),
        ("Місце встановлення", "", "Передня вісь")]


def test_full_card_goes_to_export():
    """Головний тест цієї правки: саме така картка в прогоні №18 опинилась у
    чернетці. Тепер вона мусить їхати в бойову таблицю."""
    assert missing_card(FULL, IMGS, "142124961", "341523") == []
    assert level_card(FULL, IMGS, "142124961", "341523") == 1
    assert route_card(FULL, IMGS, "142124961", "341523", "export") == (
        "export", "готово")


def test_no_photo_is_level_3_and_waits():
    assert level_card(FULL, [], "142124961", "341523") == 3
    assert route_card(FULL, [], "142124961", "341523", "export") == (
        "staging", "чекає фото")


def test_no_group_stays_in_staging():
    """Вигадати номер групи Prom не можна — неіснуючий ID ламає імпорт усього
    файлу. Тому картка без групи чекає на ручний вибір."""
    dest, status = route_card(FULL, IMGS, "", "341523", "export")
    assert dest == "staging"
    assert "групи" in status


def test_no_section_stays_in_staging():
    """Друга вісь: без підрозділу позиція є на сайті магазину, але її нема в
    пошуку самого маркетплейсу — тобто там, де її шукає покупець."""
    dest, status = route_card(FULL, IMGS, "142124961", "", "export")
    assert dest == "staging"
    assert "підрозділу" in status


def test_empty_char_values_do_not_count():
    """Три трійки з порожніми значеннями — це не три характеристики. Prom такі
    рядки просто ігнорує, і картка виходить порожньою попри «повний» вигляд."""
    chars = [("Стан", "", ""), ("Колір", "", ""), ("Матеріал", "", ""),
             ("Сумісність з маркою", "", "BMW")]
    m = missing_card(chars, IMGS, "142124961", "341523")
    assert "характеристики" in m


def test_fitment_missing_is_caught():
    """Без марки й моделі покупець не знайде позицію фасетним фільтром — а
    головна вимога власника саме в тому, щоб позиція знаходилась одразу."""
    chars = [("Стан", "", "Новий"), ("Тип техніки", "", "Легковий автомобіль"),
             ("Код запчастини", "", "31306791712")]
    m = missing_card(chars, IMGS, "142124961", "341523")
    assert "сумісність" in m
    assert route_card(chars, IMGS, "142124961", "341523", "export")[0] == "staging"


def test_empty_cross_numbers_do_not_block_original_part():
    """СВІДОМЕ рішення: OEM тут не перевіряється взагалі.

    card_builder._cross() викидає з крос-номерів власний артикул позиції. В
    оригінальної деталі BMW, у якої єдиний OEM дорівнює її ж номеру,
    «Кросс-номери» законно порожні — і якби ми вимагали їх, уся оригінальна
    лінійка назавжди лишилась би в чернетці."""
    chars = FULL + [("Кросс-номери", "", "")]
    assert missing_card(chars, IMGS, "142124961", "341523") == []


def test_describe_card_reads_like_a_sentence():
    assert describe_card(FULL, IMGS, "142124961", "341523") == "усе на місці"
    assert "фото" in describe_card(FULL, [], "142124961", "341523")


def test_staging_target_keeps_full_card_in_staging():
    """Пульт має право сказати «складай у чернетку» — рівень цього не скасовує."""
    assert route_card(FULL, IMGS, "142124961", "341523", "staging") == (
        "staging", "готово")
