# -*- coding: utf-8 -*-
"""Характеристики в РОСІЙСЬКОМУ описі — російською.

28.07. Бойовий рядок 4039 («Пильник амортизатора (переднього) BMW 3 (F30)/4
(F33)/M4 (F83)», артикул 31306791712). Назва, мета й ключовики російською
вийшли чисті, а всередині російського опису стояв український блок:

    <p>📋 <strong>Характеристики:</strong></p><ul>
      <li>Сторона монтажу: Передня вісь</li><li>Вага: 0.05 кг</li></ul>

Два різні недогляди, обидва тут перевіряються.

1. html_desc() перекладала ПІДПИСИ («Характеристики», «Аналоги / замена») і
   назву характеристики через ua2ru(), а ЗНАЧЕННЯ не чіпала взагалі. При цьому
   ua2ru зібраний під назви деталей — слів «монтажу», «вісь», «вага» в ньому
   нема, тож і назва йшла українською.

2. Валідатор цього не бачив: у _LANG_FIELDS з російських полів були лише назва
   й запити, а `description_ru` не передавався з run.py взагалі. Перевірка мови
   існувала і мовчала — найгірший вид перевірки.
"""
from adding.card_builder import html_desc, ru_char, ru_unit
from adding.rules import PROM_UNITS
from adding.validator import validate_lang
import adding.card_builder as cb

PROD = {
    "name": "Пильник амортизатора (переднього) BMW 3 (F30)/4 (F33)/M4 (F83)",
    "brand": "BMW",
    "article": "31306791712",
    "images": ["x.jpg"],
    "oe": [{"number": "31 30 6 791 712", "is_oem": True}],
    "details": {"Сторона монтажу": "Передня вісь", "Вага [кг]": "0.05"},
}

# Літери, яких у російській нема. Найпростіша перевірка «опис не українською».
UA_ONLY = "іїєґІЇЄҐ"


# ---------- переклад слів ----------
def test_назви_характеристик():
    assert ru_char("Сторона монтажу") == "Сторона монтажа"
    assert ru_char("Місце встановлення") == "Место установки"
    assert ru_char("Вага") == "Вес"
    assert ru_char("Тип запчастини") == "Тип запчасти"
    assert ru_char("Сумісність з моделлю") == "Совместимость с моделью"


def test_значення_характеристик():
    assert ru_char("Передня вісь") == "Передняя ось"
    assert ru_char("Задня вісь") == "Задняя ось"
    assert ru_char("Новий") == "Новый"
    assert ru_char("Легковий автомобіль") == "Легковой автомобиль"
    assert ru_char("Гума") == "Резина"


def test_цифри_і_латиниця_не_чіпаються():
    """Номери, кузови й марки в обох мовах пишуться однаково."""
    assert ru_char("0.05") == "0.05"
    assert ru_char("BMW 3 (F30)") == "BMW 3 (F30)"
    assert ru_char("31306791712") == "31306791712"


def test_невідоме_слово_дає_порожньо():
    """Або все, або нічого: напівпереклад у російський опис не пускаємо."""
    assert ru_char("Хитромудра характеристика") == ""


def test_порожнє_лишається_порожнім():
    assert ru_char("") == "" and ru_char(None) == ""


# ---------- одиниці ----------
def test_кожна_одиниця_prom_має_російського_двійника():
    """UNIT_RU і PROM_UNITS — той самий список. Одиниця без пари означала б
    мовчки викинутий рядок характеристики в російському описі."""
    missing = [u for u in PROM_UNITS if u not in cb.UNIT_RU]
    assert not missing, missing


def test_одиниці_перекладаються():
    assert ru_unit("кг") == "кг"
    assert ru_unit("година") == "час"
    assert ru_unit("набір") == "набор"
    assert ru_unit("невідома одиниця") == ""


# ---------- опис ----------
def test_російський_опис_без_українських_літер():
    d = html_desc(PROD, "ru")
    assert not [c for c in d if c in UA_ONLY], d
    assert "Сторона монтажа: Передняя ось" in d
    assert "Вес: 0.05 кг" in d


def test_український_опис_не_зіпсувався():
    d = html_desc(PROD, "ua")
    assert "Сторона монтажу: Передня вісь" in d
    assert "Вага: 0.05 кг" in d


def test_рядок_без_перекладу_випадає_тільки_з_російського():
    p = dict(PROD, details={"Сторона монтажу": "Передня вісь",
                            "Хитромудра характеристика": "Хитромудре значення"})
    ru, ua = html_desc(p, "ru"), html_desc(p, "ua")
    assert "Хитромудр" not in ru
    assert "Сторона монтажа" in ru
    assert "Хитромудра характеристика" in ua


def test_блоку_нема_коли_нічого_не_переклалось():
    p = dict(PROD, details={"Хитромудра характеристика": "Хитромудре значення"})
    assert "Характеристики:" not in html_desc(p, "ru")
    assert "Характеристики:" in html_desc(p, "ua")


def test_обидва_описи_про_ті_самі_характеристики():
    """Зріз до 4 пунктів робиться ДО перекладу: якби після, у російський опис
    підтягнувся б п'ятий пункт, якого в українському нема."""
    p = dict(PROD, details={"Хитромудра характеристика": "Хитромудре значення",
                            "Вага [кг]": "0.05", "Довжина [мм]": "100",
                            "Ширина [мм]": "50", "Висота [мм]": "20"})
    ru = html_desc(p, "ru")
    assert "Высота" not in ru       # п'ятий пункт — не наш
    assert "Вес: 0.05 кг" in ru


# ---------- валідатор ----------
def test_валідатор_бачить_українське_в_російському_описі():
    flags = validate_lang({"description_ru": "<li>Сторона монтажу: Передня вісь</li>"})
    assert [f for f in flags if f[2] == "lang_mix"], flags
    assert flags[0][3].startswith("опис: "), flags


def test_валідатор_перевіряє_і_мету_російською():
    flags = validate_lang({"meta_title_ru": "Пильник переднього моста",
                           "meta_desc_ru": "Пильник переднього моста BMW"})
    assert len(flags) == 2, flags
    assert {f[3].split(":")[0] for f in flags} == {"заголовок", "мета"}


def test_валідатор_мовчить_на_чистій_картці():
    assert validate_lang({"description_ru": html_desc(PROD, "ru"),
                          "description": html_desc(PROD, "ua")}) == []
