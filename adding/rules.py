_PHONE = re.compile(r"\+?380\d{9}|\b0\d{2}[\s\-]\d{3}[\s\-]?\d{2}[\s\-]?\d{2}\b")


def has_emoji(s):
    """[prom_goods] «нестандартні символи, емодзі» в назві заборонені."""
    return bool(_EMOJI.search(str(s or "")))


def has_contact(s):
    """[prom_goods] контактні дані (сайт, пошта, телефон, месенджер) заборонені
    і в назві, і в описі. Продавця покупець бачить у картці магазину."""
    t = str(s or "")
    return bool(_URL.search(t) or _MSGR.search(t) or _MAIL.search(t) or _PHONE.search(t))


def city_in(s):
    """Перше знайдене місто або ''. МІСТО і КРАЇНА — різні речі, тому дві функції.
    [prom_goods] забороняє нав'язувати регіон; «відправка по Україні» — це
    звичайна фраза про доставку, і вона під заборону не підпадає."""
    low = str(s or "").lower()
    for c in CITIES:
        if c in low:
            return c
    return ""


def country_in(s):
    low = str(s or "").lower()
    for c in COUNTRY:
        if c in low:
            return c
    return ""


def seo_words_in(s):
    """Рекламні слова у рядку (відсортовано). Підрядком — свідомо: «купити»
    шкодить і в «купити диск», і в «дискикупити»."""
    low = str(s or "").lower()
    return sorted({w for w in SEO_WORDS if w in low})


def _tokens(s):
    return [t for t in re.split(r"[^0-9a-zA-Zа-яА-ЯіїєґІЇЄҐ]+", str(s or "").lower()) if t]


def generic_only(phrase):
    """Фраза складається ТІЛЬКИ із загальних слів: «авто», «запчастини»,
    «авто запчастини». Саме така фраза — брак.

    «Автозапчастини BMW F30» браком НЕ є: там є марка й кузов, за ними покупець
    і знаходить деталь. Перевірка підрядком цієї різниці не бачила — вона
    зрізала будь-яке слово, що починається на «авто»."""
    toks = _tokens(phrase)
    return bool(toks) and all(t in _GENERIC_SET for t in toks)


def bad_words_in(s):
    """Що не так з ОДНІЄЮ фразою запиту: рекламні слова будь-де плюс фраза,
    яка цілком складається із загальних слів."""
    out = set(seo_words_in(s))
    if generic_only(s):
        out.update(_tokens(s))
    return sorted(out)


def unit_ok(u):
    """Порожня одиниця — нормально: не кожна характеристика має одиницю."""
    u = str(u or "").strip()
    return (not u) or (u in PROM_UNITS)


def gtin_valid(s):
    """[google_gtin] Довжина 8/12/13/14 І правильна контрольна цифра GS1.

    Раніше перевірялась лише довжина. Але 13 випадкових цифр — теж «довжина 13»:
    Google такий GTIN відхиляє, товар вилітає з Merchant Center, і зрозуміти
    чому — окрема пригода. Контрольна цифра рахується за mod-10: цифри справа
    наліво (без самої контрольної) множаться на 3 і 1 по черзі."""
    d = re.sub(r"\D", "", str(s or ""))
    if len(d) not in GTIN_LENGTHS:
        return False
    total = 0
    for i, ch in enumerate(reversed(d[:-1])):
        total += int(ch) * (3 if i % 2 == 0 else 1)
    return (10 - total % 10) % 10 == int(d[-1])


def availability_ok(avail, days):
    """[prom_goods] «В наявності» не можна ставити, якщо відправка довша за 3 дні.

    avail — те, що реально лежить у колонці Prom: «!» (в наявності), «+», або
    число днів під замовлення. Порівнюємо саме зі строком постачальника."""
    a = str(avail or "").strip()
    try:
        d = int(float(str(days or 0).replace(",", ".")))
    except (TypeError, ValueError):
        d = 0
    if a in ("!", "+", "в наявності", "в наличии"):
        return d <= AVAIL_MAX_DAYS_IN_STOCK
    return True


def price_ok(price):
    """[prom_goods] «некоректні "технічні" ціни (1 грн)» — окремо названа заборона.
    Порожня ціна — не сюди: її ловить окремий прапорець."""
    try:
        p = float(str(price).replace(",", ".").replace(" ", ""))
    except (TypeError, ValueError):
        return False
    return p >= PRICE_MIN_SANE


