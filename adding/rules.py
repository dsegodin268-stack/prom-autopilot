def audit_rules():
    """Правила, які має перевіряти саме ШІ. Суто кодові («ціна ≥ 2 грн») у промпт
    не йдуть: ціни в payload немає й бути не може, а зайвий рядок у системному
    промпті — це витрачена квота безкоштовного провайдера на кожній картці."""
    return [r for r in RULES if r.who in ("ші", "обидва")]


def audit_system():
    """Системний промпт аудиту, зібраний із RULES.

    Це і є та сама вимога «ШІ перевіряє за жорсткими правилами» — але без
    другої копії правил. Приберете межу тут — вона зникне і з коду, і з промпта
    одночасно, а не тихо розійдеться з ним."""
    lines = []
    for i, r in enumerate(audit_rules(), 1):
        lines.append(f"{i}. {r.text}")
    return _AUDIT_HEAD + "\n".join(lines) + "\n" + _AUDIT_TAIL


def rulebook_md():
    """Той самий довідник людською мовою — для власника й для ПРАВИЛА_PROM.md.
    Генерується, а не пишеться руками, тому не може розійтися з кодом."""
    out = ["# Жорсткі правила Prom і Google — довідник конвеєра", "",
           "Згенеровано з `adding/rules.py`. Правити треба той файл, а не цей текст.",
           "", "## Межі", ""]
    for k, (v, src) in LIMITS.items():
        url, title = source(src)
        out.append(f"- `{k}` = {v} — {title}" + (f" ({url})" if url else ""))
    out += ["", "## Правила", ""]
    for r in RULES:
        url, title = source(r.src)
        kind = "обов'язкове" if r.hard else "рекомендація"
        out.append(f"- **{r.code}** ({r.field}; перевіряє: {r.who}; {kind}) — {r.text} "
                   f"[{title}]" + (f"({url})" if url else ""))
    out += ["", "## Канон картки", "",
            "Зчитано з бойової вкладки «Export Products Sheet» (3960 позицій), "
            "не з довідки за пам'яттю. Джерело — `adding/canon.py`.", "",
            f"Розкладка: {len(canon.EXPORT_SCALARS)} скалярних колонок, далі "
            f"{canon.CHAR_SLOTS} блоків характеристик трійками "
            f"(Назва | Одиниця | Значення), перший блок — колонка "
            f"{canon.FIRST_CHAR_COL}.", "",
            "Роздільники (їх три різні, плутати не можна):", ""]
    out += [f"- `{canon.SEP_MULTI}` — {canon.CH_MODEL_FIT}, {canon.CH_YEARS}, "
            f"{canon.CH_PLACE}",
            f"- `{canon.SEP_CROSS}` — {canon.CH_CROSS}",
            f"- `{canon.IMG_SEP.strip()} ` (кома з пробілом) — Посилання_зображення", ""]
    out += ["Обов'язкові характеристики автозапчастини: " +
            ", ".join(f"`{n}`" for n in canon.CHAR_REQUIRED) + ".", "",
            "Порядок характеристик: " + " → ".join(canon.CHAR_ORDER) + ".", "",
            "Скалярні значення за замовчуванням (перевірено на всіх 3960 рядках):", ""]
    for k, v in canon.SCALAR_DEFAULTS.items():
        out.append(f"- `{k}` = `{v}`")
    out += ["", f"Довідники: груп магазину — {len(canon.CATALOG)} "
                f"(з них листкових {sum(1 for g, _n, _p in canon.CATALOG if canon.is_leaf(g))}), "
                f"розділів маркетплейсу — {len(canon.SECTIONS)}. "
                f"Номера, якого немає в довіднику, ставити не можна: неіснуючий ID "
                f"ламає імпорт усього файлу, а не однієї позиції. Запасний "
                f"підрозділ — `{canon.SECTION_FALLBACK}`.", ""]
    return "\n".join(out) + "\n"
