def group_problem(gid):
    """'' якщо група придатна, інакше — речення для звіту.

    Дві різні біди, які легко сплутати. Порожня група — це нормальний
    результат нерозпізнаного типу: картка їде в чернетку, власник обирає
    руками. А ось група, якої НЕМАЄ в довіднику магазину, — це аварія:
    неіснуючий номер ламає імпорт УСЬОГО файлу, а не однієї позиції."""
    g = str(gid or "").strip()
    if not g:
        return "група не визначена — картка на ручну курацію"
    if not canon.group_exists(g):
        return f"групи {g} немає в довіднику магазину ({GROUPS_KNOWN} груп) — імпорт впаде"
    return ""


def group_note(gid):
    """Порада, а НЕ брак: '' або речення про те, що є вужча підгрупа.

    Спокуса зробити це помилкою була, і вона хибна. У бойовій таблиці власник
    сам тримає товар у батьківських групах — у «Амортизаторы» (138537782) лежать
    47 позицій, і це свідомо: підгрупи там про пружини й опори, а сам
    амортизатор класти нікуди. Тобто «не листок» ≠ «неправильно».

    Але коли підгрупа таки пасує (відбійник — це «Пыльники и отбойники», а не
    «Амортизаторы»), позиція в батьківській групі губиться для покупця, який
    фільтрує каталог. Тому кажемо про це вголос — і лишаємо рішення людині."""
    g = str(gid or "").strip()
    if not canon.group_exists(g) or canon.is_leaf(g):
        return ""
    kids = canon.CHILDREN.get(g, ())
    names = ", ".join(f"«{canon.group_name(k)}»" for k in kids[:5])
    return (f"група {g} «{canon.group_name(g)}» має {len(kids)} підгруп ({names}) — "
            f"перевір, чи не пасує вужча: у батьківській покупець із фільтром "
            f"позицію не побачить")


def section_problem(sid, url=""):
    """'' якщо підрозділ маркетплейсу придатний, інакше — речення для звіту.

    Підрозділ — ДРУГА вісь, окрема від групи магазину: у бойовій таблиці він
    заповнений на 3960/3960 рядках і обирається за ТИПОМ ДЕТАЛІ, а не за
    групою (та сама група 142124961 має і «Пильники», і «Комплектуючі для
    фар»). Порожній підрозділ — це не дрібниця: без нього позиція не
    потрапляє у відповідний каталог Prom."""
    s = str(sid or "").strip()
    if not s:
        return "підрозділ маркетплейсу не вказаний"
    if not canon.section_exists(s):
        return f"підрозділу {s} немає в довіднику ({SECTIONS_KNOWN} розділів) — імпорт впаде"
    want = canon.section_url(s)
    have = str(url or "").strip()
    if have and have != want:
        return f"посилання підрозділу не збігається з ідентифікатором: чекали {want}"
    return ""


def chars_problem(chars):
    """'' якщо набір характеристик канонічний, інакше — речення для звіту.

    chars — [(назва, одиниця, значення)], як їх читає common/prom_format.
    Перевіряємо три речі, і кожна вже колись коштувала нам картки: чи є
    ОБОВ'ЯЗКОВІ (без «Коду запчастини» Prom не підчепить крос-довідник і
    «Сумісний транспорт» не намалюється), чи не менше мінімуму Prom, і чи не
    вилізли ми за 29 блоків — зайві common/prom_format.write_chars відкидає
    МОВЧКИ, тому переповнення видно тільки тут."""
    got = [t for t in (chars or ()) if str((list(t) + ["", "", ""])[2] or "").strip()]
    miss = canon.missing_required(got)
    if miss:
        return "бракує обов'язкових характеристик: " + ", ".join(miss)
    if len(got) < CHARS_MIN:
        return f"характеристик {len(got)}, треба щонайменше {CHARS_MIN}"
    if len(got) > CHAR_SLOTS:
        return (f"характеристик {len(got)}, а в шапці лише {CHAR_SLOTS} блоків — "
                f"зайві будуть мовчки відкинуті")
    return ""


def _solid(s):
    """Номер без пробілів і дефісів — форма, у якій його розуміє і Prom, і Google."""
    return re.sub(r"[\s\-–—]+", "", str(s or "")).strip()


def part_code_problem(chars, article):
    """'' якщо «Код запчастини» на місці й збігається з артикулом.

    Саме це поле вмикає на Prom крос-довідник OEM: заповнили — маркетплейс сам
    домальовує «Сумісний транспорт» і блок «Оригінальні номери», не заповнили —
    картка лишається німою. Номер пишеться СУЦІЛЬНО, без пробілів і дефісів."""
    val = ""
    for t in chars or ():
        nm, _u, v = (list(t) + ["", "", ""])[:3]
        if str(nm or "").strip().lower() == canon.CH_PART_CODE.lower():
            val = str(v or "").strip()
            break
    if not val:
        return f"порожня характеристика «{canon.CH_PART_CODE}» — крос-довідник Prom не спрацює"
    if re.search(r"[\s\-]", val):
        return f"«{canon.CH_PART_CODE}» = «{val}»: номер пишеться суцільно, без пробілів і дефісів"
    art = str(article or "").strip()
    # Порівнюємо СУЦІЛЬНІ форми. Інакше картка з артикулом «8K0-061-276» ловила б
    # тут вигаданий брак: у характеристиці номер за правилом стоїть без дефісів,
    # і побуквенне порівняння оголосило б це «різними номерами».
    if art and _solid(val).upper() != _solid(art).upper():
        return f"«{canon.CH_PART_CODE}» = «{val}», а Код_товару = «{art}» — це різні номери"
    return ""


# Літери, які є ЛИШЕ в українській, і ті, що є лише в російській. Слово, у
# якому зустрілись обидві ознаки — або два сусідні слова з різними ознаками в
# одному полі — означають напівпереклад.
_UA_ONLY = re.compile(r"[іїєґІЇЄҐ]")
_RU_ONLY = re.compile(r"[ыъэёЫЪЭЁ]")
# Закінчення, яких у російській не буває. Потрібні окремо, бо «переднього» не
# містить жодної суто української літери, а російським словом не є.
# «ими» сюди НЕ входить свідомо: «передними», «синими» — нормальна російська.
_UA_END = re.compile(r"\b[а-яіїєґ']+(ього|ьої|ьому|ння)\b", re.I)


def lang_mixed(s, want="ua"):
    """'' якщо поле однією мовою. Інакше — текст зауваження.

    want='ua' — поле мусить бути українським, want='ru' — російським.
    Латиниця (BMW, F30, 11427953129) не рахується: марки, кузови й каталожні
    номери пишуться латиницею в обох мовах, це не змішування мов."""
    t = str(s or "")
    if not t.strip():
        return ""
    has_ua = bool(_UA_ONLY.search(t) or _UA_END.search(t))
    has_ru = bool(_RU_ONLY.search(t))
    if has_ua and has_ru:
        return f"змішані мови в одному полі: «{t[:60]}»"
    if want == "ru" and has_ua:
        return f"російське поле написане українською: «{t[:60]}»"
    if want == "ua" and has_ru:
        return f"українське поле написане російською: «{t[:60]}»"
    return ""


# Каталожний номер, розбитий пробілами: три і більше груп цифр підряд і не
# менше 7 цифр разом. Дві групи навмисно не рахуються — це роки («2011 2019»).
_NUM_SPACED = re.compile(r"(?<![\w.,])\d+(?: \d+){2,}(?![\w])(?![.,]\d)")


def spaced_number(s):
    """'' якщо номери в тексті суцільні. Інакше — текст зауваження.

    Дзеркало card_builder._solid_nums(): там номер ЧИСТИТЬСЯ, тут — ЛОВИТЬСЯ.
    Дві функції потрібні тому, що чистять ворота, а бачити брак мусить і
    валідатор, і аудит ШІ, — інакше зауваження нема кому сформулювати."""
    for m in _NUM_SPACED.finditer(str(s or "")):
        if len(re.sub(r"\D", "", m.group(0))) >= 7:
            return (f"каталожний номер розбито пробілами: «{m.group(0)}» — "
                    f"має бути «{m.group(0).replace(' ', '')}»")
    return ""


