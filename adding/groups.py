def _text(v):
    """nodes у BM Parts буває і рядком, і списком, і списком словників.
    Раніше тут було просто конкатенування рядків — на живих даних це падало
    з TypeError і картка гинула в except усього прогону."""
    if v is None:
        return ""
    if isinstance(v, str):
        return v
    if isinstance(v, dict):
        return " ".join(_text(x) for x in v.values())
    if isinstance(v, (list, tuple, set)):
        return " ".join(_text(x) for x in v)
    return str(v)


def map_group(product):
    """(Номер_групи, Назва_групи) — сумісний зі старим кодом вигляд.

    Порожня група — це НЕ помилка, а сигнал власнику докурувати вручну:
    вигадувати ID групи Prom не можна, бо неіснуючий номер зламає імпорт."""
    gid, gname, _sid, _url = map_place(product)
    return gid, gname


def map_place(product):
    """(Номер_групи, Назва_групи, Ідентифікатор_підрозділу, Посилання_підрозділу).

    Тип не впізнано -> ('', '', '', ''): краще чернетка на ручну курацію, ніж
    вигаданий номер у бойовому фіді.

    Підрозділ ніколи не збирається «на око»: ID береться з таблиці нижче, а
    адреса — з довідника canon.SECTIONS. Якщо ID у довіднику не знайдено,
    підрозділ лишається порожнім, а не підставним, — але це вже не мовчазна
    діра: правило `section` у adding/rules.py тримає його обов'язковим, і
    картка без підрозділу поїде в чернетку."""
    hay = (_text(product.get("nodes")) + " " + _text(product.get("name"))).lower()
    for kws, gid, gname, sid in GROUPS:
        if all(k in hay for k in kws):
            return gid, gname, sid, canon.section_url(sid)
    return "", "", "", ""
