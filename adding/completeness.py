"""Рівень повноти картки — ЄДИНЕ місце, де вирішується «куди цю позицію».

Замість поділу «BM Parts проти інших постачальників» (він нічого не гарантує:
у BM Parts трапляються позиції без фото, а деталь із прайсу «Баварії» може
знайтись у каталозі BM Parts із повним набором) поділ іде за фактом —
скільки полів реально заповнено:

  Рівень 1  усе на місці           -> можна в Export (якщо пульт каже Export)
  Рівень 2  нема дрібниць, фото Є  -> завжди в Staging_Prom, людина дивиться
  Рівень 3  нема ФОТО              -> Staging_Prom, статус «чекає фото»

Чому фото — межа між 2 і 3: Prom не пропускає позицію без жодного зображення
(валідатор дає CRITICAL img_none), тому рівень 3 фізично не може поїхати в
бойовий фід, скільки б тексту не написав ШІ."""

MIN_CHARS = 3          # Prom рекомендує 2-3; для фасетних фільтрів треба ≥3
LEVEL_NAME = {1: "1 — повна", 2: "2 — без дрібниць", 3: "3 — нема фото"}


def missing(c):
    """Чого бракує картці. Порядок = порядок показу в «Огляд_Додавання»."""
    m = []
    if not c.get("photos"):
        m.append("фото")
    if len(c.get("chars") or []) < MIN_CHARS:
        m.append("характеристики")
    if not c.get("group_hint"):
        m.append("група")
    if c.get("card_loaded"):
        # картку BM Parts уже завантажено -> OEM і сумісність відомі остаточно
        if not c.get("oem"):
            m.append("OEM")
        if not c.get("fitment"):
            m.append("сумісність")
    elif not c.get("matched_bm"):
        # позиції взагалі нема в каталозі BM Parts і взяти ці поля ніде
        m += ["OEM", "сумісність"]
    # інакше: позиція з BM Parts, картку ще не тягнули — OEM і сумісність
    # прийдуть з GET /product на етапі enrich, рахувати їх браком не можна
    return m


def level(c):
    """1 / 2 / 3 за списком того, чого бракує."""
    m = missing(c)
    if not m:
        return 1
    if "фото" not in m:
        return 2
    return 3


def route(c, target):
    """(куди писати, статус) за рівнем і вибором власника в «Пульт_Додавання».

    Рівень 1 -> Export, якщо пульт каже Export.
    Рівень 2 -> Staging завжди: дрібниці має підтвердити людина.
    Рівень 3 -> Staging зі статусом «чекає фото» — у Export не поїде ніколи."""
    lv = level(c)
    if lv == 3:
        return "staging", "чекає фото"
    if lv == 2:
        return "staging", "на перевірку: нема " + ", ".join(missing(c))
    return ("export", "готово") if target == "export" else ("staging", "готово")


def describe(c):
    """Рядок для колонки «Чого бракує» в огляді."""
    m = missing(c)
    return ", ".join(m) if m else "усе на місці"
