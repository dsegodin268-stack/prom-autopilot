# 27.07. Прогін №18 показав головний дефект конвеєра: рівень і маршрут
# рахувалися з candidate — того, що прийшло з прайсу постачальника ДО того, як
# card_builder зібрав картку. Тому позиція, у якої в підсумку 10 характеристик,
# 3 фото, справжня група Prom і підрозділ, лягла в Staging з написом «на
# перевірку: нема характеристик, сумісності». Обидва твердження були брехнею —
# просто в прайсі цього не було, а в картці вже було.
#
# Тепер маршрут вирішує те, що реально поїде в таблицю: chars, images,
# Номер_групи, Ідентифікатор_підрозділу. Кандидатські level/missing/route
# лишаються без змін — на них тримається «Огляд_Додавання», де власник дивиться
# саме на сировину й вирішує, чи брати позицію взагалі.
#
# OEM тут СВІДОМО не перевіряється. card_builder._cross() викидає з крос-номерів
# власний артикул позиції, тож в оригінальної деталі BMW, у якої єдиний OEM
# дорівнює її ж номеру, «Кросс-номери» законно порожні. Перевіряти їх означало б
# назавжди лишити всю оригінальну лінійку в чернетці. Обов'язковий мінімум
# характеристик і «Код запчастини» вже стереже rules.chars_problem /
# part_code_problem через коди canon_chars і canon_part_code.

# Характеристики, що відповідають за сумісність: без жодної з них покупець не
# знайде позицію фасетним фільтром «марка / модель», а це головна вимога —
# позиція мусить знаходитись одразу.
_FIT_CHARS = ("Сумісність з маркою", "Сумісність з моделлю")


def _chars_map(chars):
    """[(назва, одиниця, значення)] -> {назва: значення} лише з непорожніми."""
    out = {}
    for row in chars or ():
        try:
            nm, _un, val = row[0], row[1], row[2]
        except (TypeError, IndexError):
            continue
        if str(nm or "").strip() and str(val or "").strip():
            out[str(nm).strip()] = str(val).strip()
    return out


def missing_card(chars=(), images=(), group_id="", section_id=""):
    """Чого бракує ГОТОВІЙ картці — тій, що ляже в таблицю.

    Порядок збігається з missing(): фото, характеристики, група, сумісність.
    Плюс «підрозділ» — друга вісь Prom (розділ маркетплейсу), без якого картка
    є на сайті магазину, але її нема в пошуку самого Prom."""
    cm = _chars_map(chars)
    m = []
    if not images:
        m.append("фото")
    if len(cm) < MIN_CHARS:
        m.append("характеристики")
    if not str(group_id or "").strip():
        m.append("група")
    if not str(section_id or "").strip():
        m.append("підрозділ")
    if not any(cm.get(k) for k in _FIT_CHARS):
        m.append("сумісність")
    return m


def level_card(chars=(), images=(), group_id="", section_id=""):
    """1 / 2 / 3 — та сама шкала, але по готовій картці."""
    m = missing_card(chars, images, group_id, section_id)
    if not m:
        return 1
    if "фото" not in m:
        return 2
    return 3


def route_card(chars, images, group_id, section_id, target):
    """(куди писати, статус) по готовій картці. Заміна route() у run.py."""
    m = missing_card(chars, images, group_id, section_id)
    if "фото" in m:
        return "staging", "чекає фото"
    if m:
        return "staging", "на перевірку: нема " + ", ".join(
            _GEN.get(x, x) for x in m)
    return ("export", "готово") if target == "export" else ("staging", "готово")


def describe_card(chars=(), images=(), group_id="", section_id=""):
    """Рядок «Чого бракує» по готовій картці."""
    m = missing_card(chars, images, group_id, section_id)
    return ", ".join(m) if m else "усе на місці"
