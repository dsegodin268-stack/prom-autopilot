def _uniq(seq):
    """Порядок зберігаємо, порожні й дублі викидаємо."""
    out, seen = [], set()
    for v in seq or ():
        s = str(v or "").strip()
        if s and s not in seen:
            seen.add(s)
            out.append(s)
    return out


