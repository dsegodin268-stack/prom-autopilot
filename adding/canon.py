def _ck(s):
    return str(s or "").strip().lower().replace("ё", "е")


_ORDER_I = {_ck(n): i for i, n in enumerate(CHAR_ORDER)}


def order_chars(chars):
    """[(назва, одиниця, значення)] -> той самий список у канонічному порядку.

    Порожні значення викидає, дублі за назвою схлопує (перший виграє),
    невідомі характеристики лишає — але ПІСЛЯ канонічних, щоб при обрізанні
    до 29 блоків першими гинули другорядні, а не «Код запчастини»."""
    seen, keep = set(), []
    for t in chars or ():
        nm, unit, val = (list(t) + ["", "", ""])[:3]
        k = _ck(nm)
        if not k or not str(val or "").strip() or k in seen:
            continue
        seen.add(k)
        keep.append((str(nm).strip(), str(unit or "").strip(), str(val).strip()))
    keep.sort(key=lambda t: _ORDER_I.get(_ck(t[0]), len(CHAR_ORDER)))
    return keep[:CHAR_SLOTS]


def missing_required(chars):
    """Яких обов'язкових характеристик бракує (порожній кортеж = все на місці)."""
    have = {_ck(t[0]) for t in (chars or ()) if str((list(t) + ["", "", ""])[2] or "").strip()}
    return tuple(n for n in CHAR_REQUIRED if _ck(n) not in have)


